/// Returns the 5x7 bitmap pattern for a given Unicode character.
/// Supports ASCII (0x20..0x7E), Turkish extended characters, and Russian Cyrillic (0x0400..0x044F, 0x0451).
pub fn lookup_glyph(ch: char) -> [u8; 7] {
    let cp = ch as u32;

    // 1. Printable ASCII range (0x20..=0x7E)
    if (0x20..=0x7E).contains(&cp) {
        return BASIC_ASCII[(cp - 0x20) as usize];
    }

    // 2. Turkish Special Characters & Cyrillic Ё/ё
    match ch {
        'Ç' => return [0x0e, 0x11, 0x10, 0x10, 0x11, 0x0e, 0x04],
        'ç' => return [0x00, 0x0e, 0x11, 0x10, 0x11, 0x0e, 0x04],
        'Ğ' => return [0x0a, 0x0e, 0x11, 0x10, 0x17, 0x11, 0x0f],
        'ğ' => return [0x0a, 0x00, 0x0f, 0x11, 0x0f, 0x01, 0x0e],
        'İ' => return [0x04, 0x0e, 0x04, 0x04, 0x04, 0x04, 0x0e],
        'ı' => return [0x00, 0x00, 0x0c, 0x04, 0x04, 0x04, 0x0e],
        'Ö' => return [0x0a, 0x0e, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'ö' => return [0x0a, 0x00, 0x0e, 0x11, 0x11, 0x11, 0x0e],
        'Ş' => return [0x0f, 0x10, 0x0e, 0x01, 0x1e, 0x04, 0x08],
        'ş' => return [0x00, 0x0e, 0x10, 0x0e, 0x01, 0x1e, 0x04],
        'Ü' => return [0x0a, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0e],
        'ü' => return [0x0a, 0x00, 0x11, 0x11, 0x11, 0x13, 0x0d],
        'Ё' => return [0x0a, 0x1f, 0x10, 0x1e, 0x10, 0x10, 0x1f],
        'ё' => return [0x0a, 0x00, 0x0e, 0x11, 0x1f, 0x10, 0x0e],
        _ => {}
    }

    // 3. Russian Cyrillic Uppercase Block (U+0410..=U+042F)
    if (0x0410..=0x042F).contains(&cp) {
        let index = (cp - 0x0410) as usize;
        return CYRILLIC_GLYPHS[index];
    }

    // 4. Russian Cyrillic Lowercase Block (U+0430..=U+044F)
    if (0x0430..=0x044F).contains(&cp) {
        let index = (cp - 0x0430 + 32) as usize;
        return CYRILLIC_GLYPHS[index];
    }

    // 5. Fallback for unhandled glyphs (box bitmap pattern)
    [0x1f, 0x11, 0x0a, 0x04, 0x0a, 0x11, 0x1f]
}


